// ------------------------------------
// RESTORE SHARED SESSION
// ------------------------------------

async function restoreSession() {
    const savedToken =
        sessionStorage.getItem(SESSION_TOKEN);

    if (!savedToken) {
        updateManagementAccess();
        return;
    }

    try {
        const result = await request(
            "me.php",
            "GET",
            null,
            savedToken
        );

        if (!result.user) {
            throw new Error(
                "Account verification failed."
            );
        }

        if (result.user.role !== "admin") {
            // Keep the customer's valid login
            // intact and return to the homepage.
            window.location.replace(
                "../index.html"
            );
            return;
        }

        await connect(savedToken);

    } catch (error) {
        // Do not delete a shared session for
        // a temporary network or PHP error.
        updateManagementAccess();

        $("managementLoginError").textContent =
            error.message;

        if (error.status === 401) {
            sessionStorage.removeItem(
                SESSION_TOKEN
            );

            sessionStorage.removeItem(
                SESSION_USER
            );

            sessionStorage.removeItem(
                VENUE_TOKEN
            );

            window.EventHubAuth?.clearSession();
        }
    }
}

