// ------------------------------------
// SHARED NAVBAR
// ------------------------------------

function attachNavbarAuth() {
    const controls = $("managementAuth");
    const nav = $("eventhub-global-nav");

    if (!controls || !nav) {
        return;
    }

    // Remove the additional Login/Logout controls
    // generated by the shared navigation.
    nav.querySelector(".eh-auth")?.remove();
    nav.querySelector(".eh-role")?.remove();

    // Reuse the existing Member 2 controls.
    if (controls.parentElement !== nav) {
        nav.appendChild(controls);
    }

    controls.hidden = false;

    controls.style.cssText = `
        display: flex;
        align-items: center;
        justify-content: flex-end;
        gap: 12px;
        grid-column: 3;
        justify-self: end;
        margin: 0;
        padding: 0;
        white-space: nowrap;
    `;

    updateNavbarAuth();
}

function updateNavbarAuth() {
    const adminLoggedIn = Boolean(
        token &&
        identity &&
        identity.role === "admin"
    );

    $("managementLoginBtn").hidden = adminLoggedIn;
    $("managementLogoutBtn").hidden = !adminLoggedIn;

    const firstName = adminLoggedIn
        ? String(identity.full_name || "Admin")
            .trim()
            .split(/\s+/)[0]
        : "";

    $("managementWelcome").textContent =
        adminLoggedIn ? "Hi, " + firstName : "";
}

// ------------------------------------
// ACCESS CONTROL
// ------------------------------------

function isAdmin() {
    return Boolean(
        token &&
        identity &&
        identity.role === "admin"
    );
}

function updateManagementAccess() {
    const allowed = isAdmin();

    $("eventAccess").hidden = allowed;
    $("eventContent").hidden = !allowed;

    $("venueAccess").hidden = allowed;
    $("venueContent").hidden = !allowed;

    $("newEventBtn").disabled = !allowed;

    $("signedInAs").textContent = allowed
        ? `${identity.full_name} (admin)`
        : "";

    updateNavbarAuth();

    if (allowed && location.hash === "#venues") {
        if (
            typeof window.openVenueWorkspace === "function"
        ) {
            window.openVenueWorkspace();
        }
    }
}

window.updateManagementAccess =
    updateManagementAccess;

// ------------------------------------
// SAVE ADMIN SESSION
// ------------------------------------

function saveAdminSession(jwt, user) {
    if (!jwt || user?.role !== "admin") {
        throw new Error(
            "Access denied. Administrator account required."
        );
    }

    sessionVersion++;

    token = jwt;
    identity = user;

    // Use the SAME login session as other pages.
    sessionStorage.setItem(SESSION_TOKEN, jwt);

    sessionStorage.setItem(
        SESSION_USER,
        JSON.stringify(user)
    );

    // Keep Member 3's embedded venue system
    // connected to the authenticated admin.
    sessionStorage.setItem(VENUE_TOKEN, jwt);

    // Remove obsolete management-only token.
    sessionStorage.removeItem(
        "eventhub_management_token"
    );

    window.EventHubAuth?.setSession(jwt, user);

    attachNavbarAuth();
    updateManagementAccess();

    // Reload the venue portal after session changes.
    if (
        typeof window.reloadVenueWorkspace === "function"
    ) {
        window.reloadVenueWorkspace();
    }
}

// ------------------------------------
// VALIDATE ADMIN JWT
// ------------------------------------

async function connect(jwt) {
    if (!jwt) {
        throw new Error(
            "Authentication token missing."
        );
    }

    const result = await request(
        "me.php",
        "GET",
        null,
        jwt
    );

    if (!result.user) {
        throw new Error(
            "Unable to verify account details."
        );
    }

    if (result.user.role !== "admin") {
        throw new Error(
            "Access denied. Only administrators " +
            "can access this management portal."
        );
    }

    saveAdminSession(jwt, result.user);
    closeLogin();

    await refreshEvents();
}

// ------------------------------------
// LOGIN WITH EMAIL AND PASSWORD
// ------------------------------------

$("managementLoginForm").addEventListener(
    "submit",
    async event => {
        event.preventDefault();

        const email = $("loginEmail").value.trim();
        const password = $("loginPassword").value;

        const button = $("loginBtn");
        button.disabled = true;

        $("managementLoginError").textContent = "";

        try {
            // Never send a previous JWT when logging in.
            const result = await request(
                "login.php",
                "POST",
                { email, password },
                ""
            );

            if (!result.token) {
                throw new Error(
                    "Login did not return a JWT token."
                );
            }

            // Verify the admin role before saving.
            await connect(result.token);

        } catch (error) {
            $("managementLoginError").textContent =
                error.message;
        } finally {
            button.disabled = false;
        }
    }
);

// ------------------------------------
// LOGOUT
// ------------------------------------

function logout() {
    sessionVersion++;

    token = "";
    identity = null;
    events = [];
    venues = [];

    // Log out from EventHub, not just Member 2.
    sessionStorage.removeItem(SESSION_TOKEN);
    sessionStorage.removeItem(SESSION_USER);

    sessionStorage.removeItem(VENUE_TOKEN);
    sessionStorage.removeItem(
        "eventhub_management_token"
    );

    window.EventHubAuth?.clearSession();

    $("totalEvents").textContent = "—";

    setStatus(
        "Not connected",
        "Please log in as administrator"
    );

    closeEventForm();
    closeLogin();

    updateManagementAccess();
    renderEvents();

    if (
        typeof window.reloadVenueWorkspace === "function"
    ) {
        window.reloadVenueWorkspace();
    }

    notice("Logged out successfully.");
}

// ------------------------------------
// LOAD EVENTS AND VENUES
// ------------------------------------

async function refreshEvents() {
    if (!isAdmin()) {
        return;
    }

    const versionAtStart = sessionVersion;

    try {
        const [eventResult, venueResult] =
            await Promise.all([
                request("events.php"),
                request("venues.php")
            ]);

        if (sessionVersion !== versionAtStart) {
            return;
        }

        events = Array.isArray(eventResult.data)
            ? eventResult.data
            : [];

        venues = Array.isArray(venueResult.data)
            ? venueResult.data
            : [];

        $("totalEvents").textContent =
            events.length;

        setStatus(
            "Connected",
            "Shared PHP REST API responding"
        );

        notice(
            `${events.length} events loaded successfully.`,
            "success"
        );

        renderEvents();

    } catch (error) {
        if (sessionVersion !== versionAtStart) {
            return;
        }

        setStatus(
            "Connection Failed",
            error.message
        );

        notice(error.message, "error");

        if (error.status === 401) {
            logout();
            notice(
                "Admin session expired. Please log in.",
                "error"
            );
        }
    }
}

// ------------------------------------
// DISPLAY EVENT RECORDS
// ------------------------------------

function renderEvents() {
    const query = $("searchInput").value
        .trim()
        .toLowerCase();

    const filtered = events.filter(event =>
        [
            event.event_id,
            event.event_name,
            event.category,
            event.status
        ].some(value =>
            String(value ?? "")
                .toLowerCase()
                .includes(query)
        )
    );

    $("resultCount").textContent =
        filtered.length + " records";

    const body = $("eventTable");
    body.replaceChildren();

    if (filtered.length === 0) {
        const row = body.insertRow();
        const cell = row.insertCell();

        cell.colSpan = 5;
        cell.className = "empty";
        cell.textContent = "No events found.";

        return;
    }

    filtered.forEach(event => {
        const row = body.insertRow();

        [
            event.event_id,
            event.event_name,
            event.organiser_id,
            event.status
        ].forEach(value => {
            const cell = row.insertCell();
            cell.textContent = value ?? "";
        });

        const actionCell = row.insertCell();

        const edit = document.createElement("button");
        edit.type = "button";
        edit.textContent = "Edit";
        edit.className =
            "btn btn-primary event-action";
        edit.disabled = !isAdmin();

        edit.addEventListener(
            "click",
            () => openEdit(event)
        );

        const remove = document.createElement("button");
        remove.type = "button";
        remove.textContent = "Delete";
        remove.className =
            "btn btn-dark event-action";
        remove.disabled = !isAdmin();

        remove.addEventListener(
            "click",
            () => deleteEvent(event)
        );

        actionCell.append(edit, remove);
    });
}

// ------------------------------------
// VENUE OPTIONS
// ------------------------------------

function fillVenues(current) {
    $("eventVenue").replaceChildren();

    venues.forEach(venue => {
        const option = document.createElement("option");

        option.value = venue.venue_id;

        option.textContent =
            `${venue.venue_name} — ${venue.city}`;

        $("eventVenue").appendChild(option);
    });

    if (current !== undefined) {
        $("eventVenue").value = String(current);
    }
}

// ------------------------------------
// EVENT FORM
// ------------------------------------

function closeEventForm() {
    $("eventForm").hidden = true;
    $("eventForm").reset();
}

function localDate(value) {
    return String(value || "")
        .replace(" ", "T")
        .substring(0, 16);
}

function openCreate() {
    if (!isAdmin()) {
        openLogin();
        return;
    }

    $("eventForm").reset();
    $("eventForm").dataset.editId = "";

    $("eventFormTitle").textContent =
        "Create Event";

    $("eventForm")
        .querySelectorAll("input, select")
        .forEach(element => {
            element.disabled = false;
        });

    fillVenues();

    $("editHint").textContent =
        "Create a new event using an available venue.";

    $("eventForm").hidden = false;

    $("eventForm").scrollIntoView({
        behavior: "smooth",
        block: "nearest"
    });
}

function openEdit(event) {
    if (!isAdmin()) {
        return;
    }

    $("eventForm").reset();

    $("eventForm").dataset.editId =
        event.event_id;

    $("eventFormTitle").textContent =
        `Edit Event #${event.event_id}`;

    $("eventName").value =
        event.event_name;

    $("eventPrice").value =
        event.ticket_price;

    $("eventCategory").value =
        event.category;

    $("eventDescription").value =
        event.description || "";

    fillVenues(event.venue_id);

    $("eventStart").value =
        localDate(event.start_date);

    $("eventEnd").value =
        localDate(event.end_date);

    [
        "eventVenue",
        "eventCategory",
        "eventStart",
        "eventEnd",
        "eventDescription"
    ].forEach(id => {
        $(id).disabled = true;
    });

    $("eventName").disabled = false;
    $("eventPrice").disabled = false;

    $("editHint").textContent =
        "The existing API updates only " +
        "event name and ticket price.";

    $("eventForm").hidden = false;

    $("eventForm").scrollIntoView({
        behavior: "smooth",
        block: "nearest"
    });
}

// ------------------------------------
// SAVE EVENT
// ------------------------------------

$("eventForm").addEventListener(
    "submit",
    async event => {
        event.preventDefault();

        if (!isAdmin()) {
            openLogin();
            return;
        }

        const id =
            $("eventForm").dataset.editId;

        const name =
            $("eventName").value.trim();

        const price =
            Number($("eventPrice").value);

        if (
            !name ||
            !Number.isFinite(price) ||
            price < 0
        ) {
            notice(
                "Enter a valid event name and price.",
                "error"
            );
            return;
        }

        let data = {
            event_name: name,
            ticket_price: price
        };

        if (!id) {
            const start =
                $("eventStart").value;

            const end =
                $("eventEnd").value;

            if (
                !start ||
                !end ||
                new Date(end) <= new Date(start)
            ) {
                notice(
                    "End date must be after start date.",
                    "error"
                );
                return;
            }

            data = {
                ...data,
                venue_id:
                    Number($("eventVenue").value),
                category:
                    $("eventCategory").value.trim(),
                description:
                    $("eventDescription").value.trim(),
                start_date:
                    start.replace("T", " ") + ":00",
                end_date:
                    end.replace("T", " ") + ":00"
            };
        }

        $("saveEventBtn").disabled = true;

        try {
            await request(
                id
                    ? `events.php?id=${encodeURIComponent(id)}`
                    : "events.php",
                id ? "PUT" : "POST",
                data
            );

            closeEventForm();
            await refreshEvents();

            notice(
                id
                    ? "Event updated successfully."
                    : "Event created successfully.",
                "success"
            );

        } catch (error) {
            notice(
                "Save failed: " + error.message,
                "error"
            );
        } finally {
            $("saveEventBtn").disabled = false;
        }
    }
);

// ------------------------------------
// DELETE EVENT
// ------------------------------------

async function deleteEvent(event) {
    if (!isAdmin()) {
        return;
    }

    const confirmed = confirm(
        `Delete event "${event.event_name}"?`
    );

    if (!confirmed) {
        return;
    }

    try {
        await request(
            `events.php?id=${encodeURIComponent(event.event_id)}`,
            "DELETE"
        );

        await refreshEvents();

        notice(
            "Event deleted successfully.",
            "success"
        );

    } catch (error) {
        notice(
            "Delete failed: " + error.message,
            "error"
        );
    }
}

